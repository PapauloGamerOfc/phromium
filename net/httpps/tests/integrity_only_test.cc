#include "net/httpps/integrity_only.h"

#include <cstdlib>
#include <iostream>
#include <numeric>

namespace {
void Check(bool value, const char* what) {
  if (!value) {
    std::cerr << "Integrity-only failure: " << what << '\n';
    std::exit(1);
  }
}

net::httpps::Bytes Unhex(std::string_view text) {
  net::httpps::Bytes out;
  const std::string_view alphabet = "0123456789abcdef";
  Check(text.size() % 2 == 0, "fixture length");
  for (size_t i = 0; i < text.size(); i += 2) {
    const auto high = alphabet.find(text[i]), low = alphabet.find(text[i + 1]);
    Check(high < 16 && low < 16, "fixture hex");
    out.push_back(static_cast<uint8_t>((high << 4) | low));
  }
  return out;
}
}  // namespace

void RunIntegrityOnlyTests() {
  using namespace net::httpps;
  const auto inner = Unhex("6e6f6e20636f6e666964656e7469616c206d657373616765170000");
  for (const uint16_t suite : {0xc0b4, 0xc0b5}) {
    const size_t size = IntegrityTagLength(suite);
    Bytes key(size), nonce(size);
    std::iota(key.begin(), key.end(), uint8_t{0});
    std::iota(nonce.begin(), nonce.end(), static_cast<uint8_t>(size));
    Bytes header{23, 3, 3, 0, static_cast<uint8_t>(inner.size() + size)};
    // Independent Python hashlib/hmac formula; not generated by RecordCipher.
    auto expected = inner;
    const auto tag = Unhex(suite == 0xc0b4
        ? "b979c3c8eea3259390cd006bab8b538611ad5f6b3904805a7e79d99f1f3cfb2c"
        : "86825d02d78ec874442c44e8db463ef124091cf163acfa432e7765379dec6da0e892cd684fd67700e890e02638036000");
    expected.insert(expected.end(), tag.begin(), tag.end());
    Bytes output;
    Check(IntegrityProtect(suite, key, nonce, header, inner, &output) && output == expected,
          "literal Protect vector, plaintext retained");
    Check(IntegrityUnprotect(suite, key, nonce, header, expected, &output) && output == inner,
          "Unprotect vector");
    for (size_t i = 0; i < expected.size(); ++i) {
      auto modified = expected;
      modified[i] ^= 1;
      output = Bytes{99};
      Check(!IntegrityUnprotect(suite, key, nonce, header, modified, &output) && output.empty(),
            "modified plaintext/tag returns no plaintext");
    }
    Check(!IntegrityUnprotect(suite, key, Bytes(size), header, expected, &output), "wrong nonce");
    Check(!IntegrityUnprotect(suite, Bytes(size), nonce, header, expected, &output), "wrong key");
    for (const size_t length : {size_t{0}, size_t{12}, size - 1, size + 1}) {
      Check(!IntegrityProtect(suite, key, Bytes(length), header, inner, &output), "nonce exact length");
      Check(!IntegrityProtect(suite, Bytes(length), nonce, header, inner, &output), "key exact length");
    }
    for (size_t i = 0; i < header.size(); ++i) {
      auto modified = header;
      modified[i] ^= 1;
      Check(!IntegrityUnprotect(suite, key, nonce, modified, expected, &output), "header bound");
    }
    header.back() = static_cast<uint8_t>(size);
    Check(IntegrityProtect(suite, key, nonce, header, {}, &output) && output.size() == size,
          "empty primitive plaintext");
    Bytes clear;
    Check(IntegrityUnprotect(suite, key, nonce, header, output, &clear) && clear.empty(),
          "empty primitive plaintext round trip");
    header.back() = static_cast<uint8_t>(size - 1);
    Check(!IntegrityUnprotect(suite, key, nonce, header, Bytes(size - 1), &clear), "truncated tag");
  }
  Bytes output{99};
  Check(!IntegrityTagLength(0x1301) &&
        !IntegrityProtect(0x1301, Bytes(32), Bytes(32), Bytes{23,3,3,0,32}, {}, &output) &&
        output.empty(), "ordinary cipher not interpreted as integrity-only");
  std::cout << "Integrity-only independent vectors and tampering tests passed\n";
}
